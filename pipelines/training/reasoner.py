def answer_jsonl(input_path: Path, output_path: Path, *, model: str, limit: int | None = None) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    total = 0
    with input_path.open(encoding="utf-8", errors="ignore") as src, output_path.open("w", encoding="utf-8") as out:
        for line in src:
            if limit is not None and total >= limit:
                break
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            question = first_text(row.get("question") or row.get("query") or row.get("prompt"))
            context = first_text(row.get("paragraph") or row.get("context") or row.get("text") or "")
            images = coerce_list(row.get("image") or row.get("images"))
            raw_answer, prediction = reasoning(question, context, data_images=images, model=model)
            result = dict(row)
            result["raw_response"] = raw_answer
            result["raw_response_tokens"] = token_length(raw_answer)
            result["predicted_answer"] = prediction
            out.write(json.dumps(result, ensure_ascii=False) + "\n")
            out.flush()
            total += 1
    print(f"Wrote {total} rows to {output_path}")


def first_text(value) -> str:
    if isinstance(value, list):
        return "" if not value else str(value[0])
    return "" if value is None else str(value)


def coerce_list(value) -> list:
    if value is None:
        return []
    if isinstance(value, list):
        return [str(item) for item in value if item]
    return [str(value)]

def extract_final_answer(text: str) -> str:
    answer_match = re.search(r"<answer>\s*(.*?)\s*</answer>", text, flags=re.DOTALL | re.IGNORECASE)
    if answer_match:
        return answer_match.group(1).strip()
    return extract_box_content(text)


def extract_box_content(text: str) -> str:
    match = None
    if re.search(r"\\box{", text):
        match = re.search(r"\\box{(.*?)}", text)
        return match.group(1) if match else text

    # 检查是否有 \boxed{}
    if re.search(r"\\boxed{", text):
        match = re.search(r"\\boxed{(.*?)}", text)
        return match.group(1) if match else text
    
    else:
        return text


def _clean_response(text):
    """Clean LLM response by removing code blocks."""
    if '```json' in text:
        return re.search(r'```json\n(.*?)```', text, re.DOTALL).group(1).strip()
    elif '```python' in text:
        return re.search(r'```python\n(.*?)```', text, re.DOTALL).group(1).strip()
    elif '```plaintext' in text:
        return re.search(r'```plaintext\n(.*?)```', text, re.DOTALL).group(1).strip()
    elif '```' in text:
        return re.search(r'```\n(.*?)```', text, re.DOTALL).group(1).strip()
    return text   

def parse_answer_r1(answer):
    cleaned_answer = re.sub(r"<think>.*?</think>", "", answer, flags=re.DOTALL).strip()

    return cleaned_answer
def parse_answer(answer):
    # 去掉 "Based on the following [Context]:" 及其后的内容
    context_pattern = r"Based on the following \[Context\]:[\s\S]*"
    cleaned_answer = re.sub(context_pattern, "", answer).strip()

    # 去掉 **final_answer** 和 **stop** 标记
    markers_pattern = r"\*\*final_answer\*\*|\*\*stop\*\*"
    cleaned_answer = re.sub(markers_pattern, "", cleaned_answer).strip()

    # 去掉 "---" 及其后的内容
    separator_pattern = r"---[\s\S]*"
    cleaned_answer = re.sub(separator_pattern, "", cleaned_answer).strip()

    return cleaned_answer


