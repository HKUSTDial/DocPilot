def build_user_prompt(question: str, data_text: str = "", data_images: list[str] | None = None) -> str:
    lines = [
        "Question:",
        question.strip(),
        "",
        "Evidence:",
        data_text.strip() or "(No text evidence provided.)",
    ]
    if data_images:
        lines.extend(["", "Visual evidence:", f"{len(data_images)} image(s) attached."])
    return "\n".join(lines)


def reasoning(
    question: str,
    data_text: str = "",
    data_images: list[str] | None = None,
    *,
    system_prompt: str,
    model: str = "gpt-4o",
) -> tuple[str, str]:
    """
    Performs reasoning based on the input question, text data, and image data.
    Uses LLM (via get_answer) to generate an answer based on the combined input.

    Args:
        question (str): The question to reason about.
        data_text (str): The relevant text data to consider.
        data_images: A list of image paths to consider.

    Returns:
        str: The answer generated by the reasoning process.
    """
    if not question:
        raise ValueError("A question must be provided.")

    prompt = build_user_prompt(question, data_text, data_images)
    image = None
    images = None
    if data_images:
        image = data_images[0] if len(data_images) == 1 else None
        images = data_images if len(data_images) > 1 else None
    answer = llm.get_answer(prompt, image=image, images=images, system_prompt=system_prompt, model=model)

    # print("question", question)
    # print("prompt", prompt)
    # print("answer", answer)
    # print("========================")
    
    final_answer = parse_answer_r1(answer)
    return answer, extract_final_answer(final_answer)


def coerce_text(value) -> str:
    if value is None:
        return ""
    if isinstance(value, (list, tuple)):
        parts = [coerce_text(v) for v in value]
        return "\n".join([part for part in parts if part])
    if isinstance(value, (dict,)):
        if "text" in value and isinstance(value["text"], str):
            return str(value["text"]).strip()
        return json.dumps(value, ensure_ascii=False)
    return str(value).strip()


def coerce_evidence_text(value) -> str:
    if value is None:
        return ""
    if isinstance(value, (list, tuple)):
        return "\n".join([coerce_text(v) for v in value if coerce_text(v)])
    if isinstance(value, (dict,)):
        if "text" in value and isinstance(value["text"], str):
            return str(value["text"]).strip()
        return json.dumps(value, ensure_ascii=False)
    return str(value).strip()


def dedup_strip_text(lines: list[str]) -> str:
    seen = set()
    items: list[str] = []
    for value in lines:
        if not value:
            continue
        normalized = "\n".join([line.strip() for line in value.splitlines() if line.strip()]) if "\n" in value else value.strip()
        if not normalized or normalized in seen:
            continue
        seen.add(normalized)
        items.append(normalized)
    return "\n\n".join(items)


def extract_row_fields(row: dict) -> tuple[str, str, list[str]]:
    question = first_text(row.get("question") or row.get("query") or row.get("prompt"))
    context = coerce_text(row.get("context"))
    if not context:
        context_parts: list[str] = [
            coerce_text(row.get("paragraph")),
            coerce_text(row.get("paragraphs")),
            coerce_text(row.get("text")),
            coerce_text(row.get("evidence")),
        ]
        context = dedup_strip_text(context_parts)

    images = coerce_list(
        row.get("image")
        or row.get("images")
        or row.get("img")
        or row.get("imgs")
        or row.get("image_paths")
        or row.get("img_paths")
        or row.get("image_path")
        or row.get("img_path")
    )
    return question, context, images


def is_finqa_or_tatqa(row: dict) -> bool:
    return any(k in row for k in ("gold_evidence", "pre_text", "post_text", "paragraphs", "answer_from", "answer_type"))


def build_output_row(row: dict, row_index: int, question: str, raw_answer: str, prediction: str, context: str) -> dict:
    if is_finqa_or_tatqa(row):
        return {
            "id": str(row.get("id", sample_id(row, row_index))),
            "question": question,
            "answer": first_text(row.get("answer")),
            "gold_evidence": coerce_evidence_text(row.get("gold_evidence") or row.get("context") or context),
            "predicted_answer": prediction,
            "raw_response": raw_answer,
            "raw_response_tokens": token_length(raw_answer),
        }

    result = dict(row)
    result["raw_response"] = raw_answer
    result["raw_response_tokens"] = token_length(raw_answer)
    result["predicted_answer"] = prediction
    return result


def distill_answer_row(row: dict, *, system_prompt: str, model: str, row_index: int) -> dict:
    question, context, images = extract_row_fields(row)
    if not question:
        raise ValueError("A question must be provided.")
    raw_answer, prediction = reasoning(
        question,
        context,
        data_images=images,
        system_prompt=system_prompt,
        model=model,
    )
    return build_output_row(row, row_index, question, raw_answer, prediction, context=context)


def answer_jsonl(
    input_path: Path,
    output_path: Path,
    *,
    model: str,
    dataset: str = "auto",
    split: str | None = None,
    limit: int | None = None,
    resume: bool = False,
    workers: int = 1,
) -> None:
    prompts = runpy.run_path(str(PROMPT_FILE))
    system_prompt = f"{prompts['SYSTEM_PROMPT'].strip()}\n\n{prompts['ANSWER_PROMPT'].strip()}"
    output_path.parent.mkdir(parents=True, exist_ok=True)
    completed = load_completed_ids(output_path) if resume else set()
    mode = "a" if resume else "w"
    total = 0
    with output_path.open(mode, encoding="utf-8") as out:
        rows: list[tuple[int, dict]] = []
        for row_index, row in enumerate(iter_input_rows(input_path, dataset=dataset, split=split)):
            if limit is not None and len(rows) >= limit:
                break
            if sample_id(row, row_index) in completed:
                continue
            rows.append((row_index, row))

        workers = max(1, int(workers))
        if workers <= 1:
            for row_index, row in tqdm(rows, desc="Distilling answer", unit="sample"):
                row_id = sample_id(row, row_index)
                try:
                    result = distill_answer_row(row, system_prompt=system_prompt, model=model, row_index=row_index)
                except Exception as exc:
                    tqdm.write(f"Failed {row_id}: {exc}")
                    continue
                out.write(json.dumps(result, ensure_ascii=False) + "\n")
                out.flush()
                total += 1
        else:
            with ThreadPoolExecutor(max_workers=workers) as executor:
                futures = {
                    executor.submit(distill_answer_row, row, system_prompt=system_prompt, model=model, row_index=row_index): (
                        row_index,
                        sample_id(row, row_index),
                    )
                    for row_index, row in rows
                }
                for future in tqdm(as_completed(futures), total=len(futures), desc="Distilling answer", unit="sample"):
                    row_index, row_id = futures[future]
                    try:
                        result = future.result()
                    except Exception as exc:
                        tqdm.write(f"Failed {row_id}: {exc}")
                        continue
                    out.write(json.dumps(result, ensure_ascii=False) + "\n")
                    out.flush()
                    total += 1
                    tqdm.write(f"[{row_id}] done")
    print(f"Wrote {total} rows to {output_path}")


def iter_input_rows(input_path: Path, *, dataset: str = "auto", split: str | None = None) -> Iterable[dict]:
    dataset = infer_dataset(input_path, dataset)
    if dataset == "infographicsvqa":
        yield from iter_infographicsvqa(input_path, split=split)
    elif dataset == "infochartqa":
        yield from iter_infochartqa(input_path, split=split)
    else:
        yield from iter_json_rows(input_path)


def infer_dataset(input_path: Path, dataset: str) -> str:
    if dataset != "auto":
        return dataset
    path_text = str(input_path).lower()
    if "infographicsvqa" in path_text or "inforgraphicsvqa" in path_text:
        return "infographicsvqa"
    if "infochartqa" in path_text:
        return "infochartqa"
    return "jsonl"


def iter_json_rows(input_path: Path) -> Iterable[dict]:
    text = input_path.read_text(encoding="utf-8", errors="ignore").lstrip()
    if not text:
        return
    if text.startswith("["):
        data = json.loads(text)
        for row in data:
            yield row
        return
    if text.startswith("{"):
        data = json.loads(text)
        if isinstance(data, dict) and isinstance(data.get("data"), list):
            yield from data["data"]
        else:
            yield data
        return
    for line in text.splitlines():
        if line.strip():
            yield json.loads(line)


def iter_infographicsvqa(input_path: Path, *, split: str | None = None) -> Iterable[dict]:
    root = resolve_infographicsvqa_root(input_path)
    splits = split_names(split, default=["train", "val"])
    files = {
        "train": root / "infographicsvqa_qas/infographicsVQA_train_v1.0.json",
        "val": root / "infographicsvqa_qas/infographicsVQA_val_v1.0_withQT.json",
        "test": root / "infographicsvqa_qas/infographicsVQA_test_v1.0.json",
    }
    if input_path.is_file():
        files = {"custom": input_path}
        splits = ["custom"]

    for split_name in splits:
        path = files[split_name]
        payload = json.loads(path.read_text(encoding="utf-8", errors="ignore"))
        for row in payload.get("data", []):
            image_name = row.get("image_local_name")
            image_path = root / "images" / str(image_name) if image_name else None
            converted = dict(row)
            converted["id"] = str(row.get("questionId", row.get("id", "")))
            converted["source_dataset"] = "InforGraphicsVQA"
            converted["source_split"] = row.get("data_split", split_name)
            converted["image"] = str(image_path) if image_path and image_path.exists() else row.get("image_url")
            converted["answer"] = first_text(row.get("answers"))
            yield converted


def resolve_infographicsvqa_root(input_path: Path) -> Path:
    if input_path.is_dir():
        return input_path
    if input_path.parent.name == "infographicsvqa_qas":
        return input_path.parent.parent
    return INFOGRAPHICSVQA_ROOT


def iter_infochartqa(input_path: Path, *, split: str | None = None) -> Iterable[dict]:
    data_dir = resolve_infochartqa_data_dir(input_path)
    splits = split_names(split, default=["text", "visual_basic", "visual_metaphor"])
    for path in infochartqa_files(data_dir, splits):
        for row in iter_parquet_rows(path):
            question = first_text(row.get("question"))
            instructions = first_text(row.get("instructions"))
            if instructions:
                question = f"{question}\n\nInstructions:\n{instructions}"
            converted = dict(row)
            converted["id"] = str(row.get("question_id", row.get("id", "")))
            converted["source_dataset"] = "InfoChartQA"
            converted["source_split"] = path.name.split("-", 1)[0]
            converted["question"] = question
            converted["image"] = row.get("url")
            converted["context"] = infochartqa_context(row)
            yield converted


def resolve_infochartqa_data_dir(input_path: Path) -> Path:
    if input_path.is_file():
        return input_path.parent
    if (input_path / "dataset/data").exists():
        return input_path / "dataset/data"
    if (input_path / "data").exists():
        return input_path / "data"
    return input_path


def infochartqa_files(data_dir: Path, splits: list[str]) -> list[Path]:
    if data_dir.is_file():
        return [data_dir]
    files: list[Path] = []
    for split_name in splits:
        files.extend(sorted(data_dir.glob(f"{split_name}-*.parquet")))
    return files


def iter_parquet_rows(path: Path) -> Iterable[dict]:
    try:
        import pyarrow.parquet as pq
    except ImportError:
        import pandas as pd
        for row in pd.read_parquet(path).to_dict(orient="records"):
            yield row
        return
    parquet = pq.ParquetFile(path)
    columns = parquet.schema_arrow.names
    for batch in parquet.iter_batches(columns=columns, batch_size=256):
        for row in batch.to_pylist():
            yield row


def infochartqa_context(row: dict) -> str:
    parts = []
    for key in ("question_type_name", "data_fact", "difficulty", "chart_type"):
        value = row.get(key)
        if value:
            parts.append(f"{key}: {value}")
    bboxes = row.get("extra_input_figure_bboxes") or []
    if bboxes:
        parts.append(f"extra_input_figure_bboxes: {json.dumps(bboxes, ensure_ascii=False)}")
    return "\n".join(parts)


def split_names(split: str | None, *, default: list[str]) -> list[str]:
    if not split:
        return default
    return [item.strip() for item in split.split(",") if item.strip()]


def first_text(value) -> str:
    if isinstance(value, list):
        return "" if not value else str(value[0])
    return "" if value is None else str(value)


def coerce_list(value) -> list:
    if value is None:
        return []
    if isinstance(value, list):
        return [str(item) for item in value if item]
    return [str(value)]


def sample_id(row: dict, fallback: int) -> str:
    if "id" in row:
        return str(row["id"])
    if "_id" in row:
        return str(row["_id"])
    return str(fallback)


def load_completed_ids(path: Path) -> set[str]:
    if not path.exists():
        return set()
    completed = set()
    with path.open(encoding="utf-8", errors="ignore") as stream:
        for line_number, line in enumerate(stream, start=1):
            if not line.strip():
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"Invalid JSONL at {path}:{line_number}") from exc
            completed.add(sample_id(row, line_number - 1))
    return completed


def extract_final_answer(text: str) -> str:
    answer_match = re.search(r"<answer>\s*(.*?)\s*</answer>", text, flags=re.DOTALL | re.IGNORECASE)
    if answer_match:
        return answer_match.group(1).strip()
    return extract_box_content(text)


def extract_box_content(text: str) -> str:
    match = None
    if re.search(r"\\box{", text):
        match = re.search(r"\\box{(.*?)}", text)
        return match.group(1) if match else text

    # 检查是否有 \boxed{}
    if re.search(r"\\boxed{", text):
        match = re.search(r"\\boxed{(.*?)}", text)
        return match.group(1) if match else text
    
    else:
        return text


def _clean_response(text):
    """Clean LLM response by removing code blocks."""
    if '```json' in text:
        return re.search(r'```json\n(.*?)```', text, re.DOTALL).group(1).strip()
    elif '```python' in text:
        return re.search(r'```python\n(.*?)```', text, re.DOTALL).group(1).strip()
    elif '```plaintext' in text:
        return re.search(r'```plaintext\n(.*?)```', text, re.DOTALL).group(1).strip()
    elif '```' in text:
        return re.search(r'```\n(.*?)```', text, re.DOTALL).group(1).strip()
    return text   

def parse_answer_r1(answer):
    cleaned_answer = re.sub(r"<think>.*?</think>", "", answer, flags=re.DOTALL).strip()

    return cleaned_answer
def parse_answer(answer):
    # 去掉 "Based on the following [Context]:" 及其后的内容
    context_pattern = r"Based on the following \[Context\]:[\s\S]*"
    cleaned_answer = re.sub(context_pattern, "", answer).strip()

    # 去掉 **final_answer** 和 **stop** 标记
    markers_pattern = r"\*\*final_answer\*\*|\*\*stop\*\*"
    cleaned_answer = re.sub(markers_pattern, "", cleaned_answer).strip()

    # 去掉 "---" 及其后的内容
    separator_pattern = r"---[\s\S]*"
    cleaned_answer = re.sub(separator_pattern, "", cleaned_answer).strip()

    return cleaned_answer


